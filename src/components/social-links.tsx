const ICONS = {
  instagram: IconInstagram,
  linkedin: IconLinkedIn,
  tiktok: IconTikTok,
  x: IconX,
} as const;

const LABELS = {
  instagram: "Instagram",
  linkedin: "LinkedIn",
  tiktok: "TikTok",
  x: "X",
} as const;

export function SocialLinksRow({
  social,
  className = "",
}: {
  social: SocialLinks;
  className?: string;
}) {
  const keys = activeSocialLinks(social);
  if (!keys.length) return null;

  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {keys.map((key) => {
        const Icon = ICONS[key];
        return (
          <a
            key={key}
            href={social[key]}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={LABELS[key]}
            className="inline-flex size-10 items-center justify-center rounded-full border border-white/15 bg-white/5 text-white/80 transition-colors hover:border-gold hover:text-gold"
          >
            <Icon className="size-4" />
          </a>
        );
      })}
    </div>
  );
}
